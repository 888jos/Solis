import { defineTable } from "convex/server";
import { v } from "convex/values";

// Owner: carousels agent. Mirror of the Carousel Factory (~/app/carousel-factory) that runs on Jos's Mac:
// `cf sync` pushes accounts, the day plans and every rendered carousel (slides in file storage), and pulls
// back the review decisions taken here. The Mac stays the source of truth; Solis only adds decisions.
export const contentTables = {
  carouselAccounts: defineTable({
    name: v.string(), // TikTok handle without @
    persona: v.string(),
    series: v.string(),
    startDate: v.string(), // first posting day (YYYY-MM-DD), "" = not started
    slots: v.array(v.string()), // posting times, New York
    perDay: v.number(), // carousels per day after warm-up
    warmupDays: v.number(), // 1 carousel per day, no app mention, during the first N days
    position: v.number(), // order in the config file
    syncedAt: v.number(),
  }).index("by_name", ["name"]),

  carouselPlan: defineTable({
    itemId: v.string(), // {date}-{account}-{slot index}
    date: v.string(),
    account: v.string(),
    slot: v.string(),
    hookId: v.string(),
    hook: v.string(),
    family: v.string(),
    familyName: v.string(),
    template: v.string(),
    templateName: v.string(),
    mentionApp: v.boolean(),
    integration: v.string(),
    integrationName: v.string(),
    series: v.optional(v.string()),
    status: v.string(), // planned | generated | failed | in_review | approved | rejected | redo | published
    carouselId: v.optional(v.string()),
    error: v.optional(v.string()),
    syncedAt: v.number(),
  })
    .index("by_item", ["itemId"])
    .index("by_date", ["date"]),

  carousels: defineTable({
    cid: v.string(),
    account: v.string(),
    template: v.string(),
    templateName: v.string(),
    topic: v.string(),
    status: v.string(), // rendered | qa_failed | in_review | approved | rejected | redo | published
    slideCount: v.number(),
    caption: v.string(),
    qaStatus: v.string(), // pass | warn | fail
    qaIssues: v.array(v.object({ level: v.string(), msg: v.string(), slide: v.optional(v.number()) })),
    hookOptions: v.array(v.string()),
    scores: v.optional(v.record(v.string(), v.number())), // Claude's rubric, when generated by Claude
    planItemId: v.optional(v.string()),
    slides: v.array(v.id("_storage")), // JPEGs resized for the web, in order
    slidesHash: v.string(), // hash of the local files, so unchanged slides are never uploaded twice
    createdAt: v.number(),
    updatedAt: v.number(),
    // A decision taken in Solis waits here until `cf sync` applies it on the Mac.
    decisionPending: v.boolean(),
    decision: v.optional(v.object({ status: v.string(), at: v.number() })),
  })
    .index("by_cid", ["cid"])
    .index("by_created", ["createdAt"])
    .index("by_status_created", ["status", "createdAt"])
    .index("by_decision_pending", ["decisionPending"]),
};
